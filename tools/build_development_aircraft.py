def f(value: float) -> str:
    return f"{value:.9f}"


def set_value(replacements: dict[str, str], key: str, value: str | float | int) -> None:
    replacements[key] = str(value) if isinstance(value, (str, int)) else f(value)


def wing_pair(
    replacements: dict[str, str],
    indexes: tuple[int, int],
    *,
    root: float,
    tip: float,
    semilen: float,
    sweep: float,
    dihedral: float,
    x: float,
    y: float,
    z: float,
    incidence_root: float,
    incidence_tip: float,
) -> None:
    for pair_side, wing_index in enumerate(indexes):
        sign = -1.0 if pair_side == 0 else 1.0
        prefix = f"_wing/{wing_index}"
        set_value(replacements, f"{prefix}/_Croot", root)
        set_value(replacements, f"{prefix}/_Ctip", tip)
        set_value(replacements, f"{prefix}/_semilen_SEG", semilen)
        set_value(replacements, f"{prefix}/_sweep_design", sweep)
        set_value(replacements, f"{prefix}/_dihed_design", dihedral)
        set_value(replacements, f"{prefix}/_part_x", sign * x)
        set_value(replacements, f"{prefix}/_part_y", y)
        set_value(replacements, f"{prefix}/_part_z", z)
        for station in range(10):
            ratio = station / 9.0
            incidence = incidence_root + ratio * (incidence_tip - incidence_root)
            set_value(replacements, f"{prefix}/_incidence/{station}", incidence)


def object_attachment(
    index: int,
    path: str,
    *,
    x: float,
    y: float,
    z: float,
    psi: float = 0.0,
    obj_flags: int = 24,
    is_internal: bool = False,
) -> list[str]:
    prefix = f"P _obja/{index}"
    return [
        f"{prefix}/_obj_flags {obj_flags}\n",
        f"{prefix}/_v10_att_body -1\n",
        f"{prefix}/_v10_att_file_stl {path}\n",
        f"{prefix}/_v10_att_gear -1\n",
        f"{prefix}/_v10_att_phi_ref 0.000000000\n",
        f"{prefix}/_v10_att_psi_ref {f(psi)}\n",
        f"{prefix}/_v10_att_the_ref 0.000000000\n",
        f"{prefix}/_v10_att_wing -1\n",
        f"{prefix}/_v10_att_x_acf_prt_ref {f(x)}\n",
        f"{prefix}/_v10_att_y_acf_prt_ref {f(y)}\n",
        f"{prefix}/_v10_att_z_acf_prt_ref {f(z)}\n",
        f"{prefix}/_v10_is_internal {int(is_internal)}\n",
        f"{prefix}/_v10_steers_with_gear 0\n",
    ]


def build_replacements() -> dict[str, str]:
    r: dict[str, str] = {}

    # Identity and source-derived operating limits.
    set_value(r, "acf/_ICAO", "A388")
    set_value(r, "acf/_name", "A380X XP12 Development Build")
    set_value(r, "acf/_descrip", "FlyByWire A380-842 source conversion - development flight model")
    set_value(r, "acf/_author", "FlyByWire source assets; independent X-Plane conversion workbench")
    set_value(r, "acf/_manufacturer", "Airbus")
    set_value(r, "acf/_studio", "Non-commercial open-source development build")
    set_value(r, "acf/_tailnum", "F-WWDD")
    set_value(r, "acf/_version", "0.1-dev")
    set_value(r, "acf/_Mmo", 0.89)
    set_value(r, "acf/_Vno_kts", 340)
    set_value(r, "acf/_Vne_kts", 365)
    set_value(r, "acf/_Vfe1_kts", 250)
    set_value(r, "acf/_Vfem_kts", 180)

    # X-Plane stores these mass values in pounds.
    set_value(r, "acf/_m_empty", 300_007 * KG_TO_LB)
    set_value(r, "acf/_m_fuel_max_tot", 323_546 * KG_TO_LB)
    set_value(r, "acf/_m_max", 510_000 * KG_TO_LB)
    set_value(r, "acf/_num_engn", 4)
    set_value(r, "acf/_bypass_ratio", 8.7)
    set_value(r, "acf/_thrust_max_limit", 80_213)
    # Let X-Plane derive spring and damping behavior from the finished aircraft
    # mass and gear geometry. The inherited 747 custom curves were evaluated
    # against a much lighter/different load distribution and caused a severe
    # runway-start rebound in the A380-sized model.
    set_value(r, "acf/_use_cus_gear_damping", 0)
    set_value(r, "acf/_use_cus_gear_defs", 0)

    # X-Plane 12.2 split the airliner parking brake into master-cylinder
    # pressure and a hydraulic valve. The inherited 747 scaffold predates
    # that model and describes a mechanically locking brake handle instead.
    # On 12.4 that can leave applied brake pressure behind after the release
    # command even though the requested park-brake ratio has reached zero.
    # The A380 uses a pressure-trapping valve, and toe-brake input is not its
    # parking-brake release mechanism.
    set_value(r, "acf/_hyd_park_brake_trap", 1)
    set_value(r, "acf/_hyd_park_brake_toe", 0)

    # FBW flight_model.cfg: empty_weight_CG_position = 16, 0, 2.8 ft.
    # MSFS longitudinal coordinates increase forward; the X-Plane datum is the
    # nose and its longitudinal coordinates increase aft. The MSFS reference
    # datum is not the empty-weight CG.
    cg_z = MSFS_NOSE_LONGITUDINAL_FT - 16.0
    set_value(r, "acf/_cgY", 2.8)
    set_value(r, "acf/_cgZ", cg_z)
    set_value(r, "acf/_cgZ_fwd", cg_z - 4.5)
    set_value(r, "acf/_cgZ_aft", cg_z + 5.5)
    # X-Plane applies this cached pose before its suspension solver runs.  It
    # must be expressed as CG height above the contact plane; copying MSFS's
    # 14.30 ft static-CG-height field directly embeds this model in the runway.
    # The small suspension settling from the previous 18.55 ft pose stayed
    # below the crash threshold in the native reference run.
    set_value(r, "acf/_h_eqlbm", XPLANE_EQUILIBRIUM_HEIGHT_FT)
    set_value(r, "acf/_the_eqlbm", XPLANE_EQUILIBRIUM_PITCH_DEG)

    # Pilot eyes in the FBW cockpit shell. The source cockpit is around
    # longitudinal z=32 m; after the whole-model 180-degree attachment at the
    # 35.085 m datum its flight-deck eye point is about 3.1 m from the nose.
    set_value(r, "acf/_pe_xyz/0", -1.74)
    set_value(r, "acf/_pe_xyz/1", 10.50)
    set_value(r, "acf/_pe_xyz/2", 10.10)
    set_value(r, "acf/_pe_xyz_copilot/0", 1.74)
    set_value(r, "acf/_pe_xyz_copilot/1", 10.50)
    set_value(r, "acf/_pe_xyz_copilot/2", 10.10)

    # Source control travel limits. The experimental FBW script remains off by default.
    for surface in ("ailn1", "ailn2", "elev1", "elev2"):
        set_value(r, f"acf/_{surface}_up", 30)
        set_value(r, f"acf/_{surface}_dn", 30)
    for surface in ("rudd1", "rudd2"):
        set_value(r, f"acf/_{surface}_lf", 30)
        set_value(r, f"acf/_{surface}_rt", 30)
    set_value(r, "acf/_stab_trim_up", 10)
    set_value(r, "acf/_stab_trim_dn", 2)
    set_value(r, "acf/_sbrk1_up_flit", 45)
    set_value(r, "acf/_sbrk1_up_grnd", 50)
    set_value(r, "acf/_spoi1_with_flit_sbrk", 45)
    set_value(r, "acf/_spoi1_with_grnd_sbrk", 50)

    # Four Trent 972B-84 positions from FBW engines.cfg. MSFS order is
    # longitudinal, lateral, vertical; X-Plane order here is x, y, z.
    engine_source = [
        (-10.0, -84.0, -1.5),
        (15.0, -47.5, -4.0),
        (15.0, 47.5, -4.0),
        (-10.0, 84.0, -1.5),
    ]
    for index, (longitudinal, lateral, vertical) in enumerate(engine_source):
        prefix = f"_engn/{index}"
        set_value(r, f"{prefix}/_part_x", lateral)
        set_value(r, f"{prefix}/_part_y", vertical)
        set_value(r, f"{prefix}/_part_z", MSFS_NOSE_LONGITUDINAL_FT - longitudinal)
        set_value(r, f"{prefix}/_thrust_max_limit", 80_213)

        # Keep the scaffold's invisible nacelle drag bodies, but move them to
        # the A380 stations. They are not visual assets.
        body_index = 21 + index
        set_value(r, f"_body/{body_index}/_part_x", lateral)
        set_value(r, f"_body/{body_index}/_part_y", vertical)
        set_value(r, f"_body/{body_index}/_part_z", MSFS_NOSE_LONGITUDINAL_FT - longitudinal)

    # Main wing: four trapezoidal panels per side. This gives 841.74 m^2,
    # within 0.4% of FBW's 845.046 m^2 reference, and the exact 79.75092 m span.
    span_segments = (45.0, 20.0, 38.0, 27.825)
    chords = (58.86, 47.0, 34.0, 18.5, 6.0)
    root_y = 0.96
    root_z = MSFS_NOSE_LONGITUDINAL_FT - 51.91
    x_station = 0.0
    y_station = root_y
    z_station = root_z
    incidences = ((2.0, 1.0), (1.0, 0.0), (0.0, -2.0), (-2.0, -3.5))
    for segment, indexes in enumerate(((0, 1), (2, 3), (4, 5), (6, 7))):
        wing_pair(
            r,
            indexes,
            root=chords[segment],
            tip=chords[segment + 1],
            semilen=span_segments[segment],
            sweep=33.5,
            dihedral=5.6,
            x=x_station,
            y=y_station,
            z=z_station,
            incidence_root=incidences[segment][0],
            incidence_tip=incidences[segment][1],
        )
        x_station += span_segments[segment]
        y_station += math.tan(math.radians(5.6)) * span_segments[segment]
        z_station += math.tan(math.radians(33.5)) * span_segments[segment]

    # Horizontal tail: 148.92 m^2 and 30.358 m span.
    htail_semispan = 30.35808 * FT_PER_M / 2.0
    htail_tip_z = MSFS_NOSE_LONGITUDINAL_FT - (-123.13)
    htail_root_z = htail_tip_z - math.tan(math.radians(35.0)) * htail_semispan
    htail_root_y = 17.53 - math.tan(math.radians(5.0)) * htail_semispan
    wing_pair(
        r,
        (8, 9),
        root=25.8,
        tip=6.4,
        semilen=htail_semispan,
        sweep=35.0,
        dihedral=5.0,
        x=0.0,
        y=htail_root_y,
        z=htail_root_z,
        incidence_root=0.0,
        incidence_tip=-1.0,
    )

    # Two vertical aerodynamic panels share the source's total fin area.
    vtail_span = 14.590776 * FT_PER_M
    vtail_tip_z = MSFS_NOSE_LONGITUDINAL_FT - (-123.27)
    vtail_root_z = vtail_tip_z - math.tan(math.radians(43.0)) * vtail_span
    for offset, wing_index in enumerate((10, 11)):
        prefix = f"_wing/{wing_index}"
        set_value(r, f"{prefix}/_Croot", 38.0)
        set_value(r, f"{prefix}/_Ctip", 20.0)
        set_value(r, f"{prefix}/_semilen_SEG", vtail_span)
        set_value(r, f"{prefix}/_sweep_design", 43.0)
        set_value(r, f"{prefix}/_dihed_design", 90.0)
        set_value(r, f"{prefix}/_part_x", 0.0)
        set_value(r, f"{prefix}/_part_y", 66.496658 - vtail_span)
        set_value(r, f"{prefix}/_part_z", vtail_root_z + offset * 0.1)

    # Contact-point order deliberately makes index 3 the left body gear,
    # matching the converted glTF object's deploy_ratio[3] animation.
    gear = [
        # name, lateral x, longitudinal, contact y, radius, leg, type, steer, brakes
        ("nose", 0.0, 99.15, XPLANE_NOSE_CONTACT_FT, 2.239, 8.50, 3, 70.0, 0),
        ("left_wing", -23.0, 5.7, -15.63, 2.356, 7.80, 5, 0.0, 1),
        ("right_wing", 23.0, 5.7, -15.63, 2.356, 7.80, 5, 0.0, 1),
        ("left_body", -11.5, -5.7, XPLANE_BODY_CONTACT_FT, 2.356, 7.00, 6, 8.0, 1),
        ("right_body", 11.5, -5.7, XPLANE_BODY_CONTACT_FT, 2.356, 7.00, 6, 8.0, 1),
    ]
    for index, (
        _, lateral, longitudinal, contact_y, radius, leg, gear_type, steer, brakes
    ) in enumerate(gear):
        prefix = f"_gear/{index}"
        # The scaffold used a four-wheel 747 truck for every main assembly and
        # retained large truck-tilt values.  A380 body bogies have six wheels;
        # the incorrect truck geometry was supporting the aircraft aft of its
        # intended contact points and leaving the nose gear airborne.  Neutral
        # truck angles make the coordinates below the authoritative ground
        # contact geometry.
        set_value(r, f"{prefix}/_gear_type", gear_type)
        set_value(r, f"{prefix}/_eagle_claw_deg", 0.0)
        set_value(r, f"{prefix}/_gear_x", lateral)
        set_value(r, f"{prefix}/_gear_y", contact_y + radius + leg)
        set_value(r, f"{prefix}/_gear_z", MSFS_NOSE_LONGITUDINAL_FT - longitudinal)
        set_value(r, f"{prefix}/_latE", 0.0)
        set_value(r, f"{prefix}/_lonE", 0.0)
        set_value(r, f"{prefix}/_leg_len", leg)
        set_value(r, f"{prefix}/_tire_radius", radius)
        set_value(r, f"{prefix}/_tire_swidth", 1.00 if index else 0.85)
        set_value(r, f"{prefix}/_steerdeg_lospeed", steer)
        set_value(r, f"{prefix}/_steerdeg_hispeed", min(7.0, steer))
        set_value(r, f"{prefix}/_gear_brakes", brakes)
        set_value(r, f"{prefix}/_cyc_time", 20.0)
        set_value(r, f"{prefix}/_damp", 60_000 if index == 0 else 120_000)
        set_value(r, f"{prefix}/_strut_max_wgt_frc", 130_000 if index == 0 else 300_000)
        set_value(r, f"{prefix}/_strut_preload_frc", 30_000 if index == 0 else 140_000)

    return r


def transform_acf(
    template: Path,
    exterior_object_paths: list[str] | None = None,
    interior_object_paths: list[str] | None = None,
    cockpit_object_path: str | None = None,
    legacy_gear: bool = True,
    panel_3d_lines: list[str] | None = None,
) -> tuple[list[str], dict[str, object]]:
    lines = template.read_text(encoding="latin1").splitlines(keepends=True)
    exterior_object_paths = exterior_object_paths or []
    interior_object_paths = interior_object_paths or []
    replacements = build_replacements()
    found: set[str] = set()
    result: list[str] = []
    inserted_objects = False
    in_panel_3d = False
    legacy_paths = ['gear-body-lh/a380x_gear_body_lh.obj',
                    'gear-body-lh/a380x_gear_body_lh_tires.obj'] if legacy_gear else []

    # Scale the invisible Plane Maker fuselage to A380 dimensions. This affects
    # drag/volume, not the visible FBW-derived OBJ geometry.
    fuselage_scale = (1.11, 1.02, 238.378 / 224.083770752)
    nacelle_scale = (0.96, 0.96, 0.72)

    for line in lines:
        stripped = line.rstrip("\r\n")

        if stripped == "PANEL_3D_BEGIN":
            in_panel_3d = True
            result.append("PANEL_3D_BEGIN\n")
            if panel_3d_lines:
                result.extend(
                    line if line.endswith(('\n', '\r')) else line + '\n'
                    for line in panel_3d_lines
                )
            continue
        if in_panel_3d:
            if stripped == "PANEL_3D_END":
                in_panel_3d = False
                result.append("PANEL_3D_END\n")
            continue

        if stripped.startswith("P acf/_ann_wav_file/"):
            if stripped.startswith("P acf/_ann_wav_file/count "):
                result.append("P acf/_ann_wav_file/count 0\n")
            continue

        # The two outer glareshield knobs control independent left/right
        # instrument-panel flood spots; the center spot remains on channel 0.
        if stripped == "P acf/_spot_name_3d/1 sim/cockpit2/electrical/panel_brightness_ratio[0]":
            result.append("P acf/_spot_name_3d/1 sim/cockpit2/electrical/panel_brightness_ratio[1]\n")
            continue
        if stripped == "P acf/_spot_name_3d/2 sim/cockpit2/electrical/panel_brightness_ratio[0]":
            result.append("P acf/_spot_name_3d/2 sim/cockpit2/electrical/panel_brightness_ratio[2]\n")
            continue

        if stripped.startswith("P _obja/"):
            if not inserted_objects:
                body_gear_z = MSFS_NOSE_LONGITUDINAL_FT - (-5.7)
                # Compatibility with early one-gear builds only. Complete
                # FBW assemblies use ATTACH_CENTER, like the main exterior.
                for object_index, object_path in enumerate(legacy_paths):
                    result.extend(object_attachment(
                        object_index, object_path,
                        x=-11.5,
                        y=-12.4,
                        z=body_gear_z,
                    ))
                for object_index, object_path in enumerate(exterior_object_paths, start=len(legacy_paths)):
                    nose_moving_part = object_path.startswith("exterior/gear-nose/") and not object_path.endswith("_lg_bay.obj")
                    result.extend(
                        object_attachment(
                            object_index,
                            object_path,
                            x=0.0,
                            y=NOSE_ASSEMBLY_Y_FT if nose_moving_part else 0.0,
                            z=MSFS_NOSE_LONGITUDINAL_FT,
                            # FBW's glTF is +X left and +Z forward after the
                            # standard Blender import. X-Plane is +X right and
                            # +Z aft, so rotate the complete model 180 degrees.
                            psi=180.0,
                        )
                    )
                interior_start = len(legacy_paths) + len(exterior_object_paths)
                for object_index, object_path in enumerate(
                    interior_object_paths, start=interior_start
                ):
                    result.extend(
                        object_attachment(
                            object_index,
                            object_path,
                            x=0.0,
                            y=0.0,
                            z=MSFS_NOSE_LONGITUDINAL_FT,
                            psi=180.0,
                            # The stock 747 cockpit used flags 13 for an
                            # internal cockpit object; keep the same X-Plane
                            # visibility class for the converted FBW shell.
                            obj_flags=13,
                            is_internal=True,
                        )
                    )
                object_count = interior_start + len(interior_object_paths)
                if cockpit_object_path:
                    result.extend(
                        object_attachment(
                            object_count,
                            cockpit_object_path,
                            x=0.0,
                            y=0.0,
                            z=MSFS_NOSE_LONGITUDINAL_FT,
                            psi=180.0,
                            # X-Plane restricts manipulators to the one object
                            # marked as the cockpit object. Bit 2048 adds that
                            # role to the same internal-view flags used above.
                            obj_flags=2061,
                            is_internal=True,
                        )
                    )
                    object_count += 1
                result.append(
                    f"P _obja/count {object_count}\n"
                )
                inserted_objects = True
            continue

        # Disable leftover 747 auxiliary aerodynamic parts. Keep fuselage body
        # 0 and the four invisible nacelle bodies 21-24.
        body_eq = re.match(r"P _body/(\d+)/_part_specs_eq ", stripped)
        if body_eq and int(body_eq.group(1)) not in (0, 21, 22, 23, 24):
            result.append(f"P _body/{body_eq.group(1)}/_part_specs_eq 0\n")
            continue
        # Do not leave disabled wings serialized with non-zero geometry. In
        # X-Plane 12.4.3 those slots can still reach the finite-wing solver,
        # but their airfoil pointers are not initialized when part_specs_eq is
        # zero. The resulting null mid-foil lookup crashes the simulator.
        inactive_wing = re.match(r"P _wing/(\d+)/", stripped)
        if inactive_wing and int(inactive_wing.group(1)) >= 12:
            continue

        geo = re.match(r"P _body/(0|21|22|23|24)/_geo_xyz/([^ ]+) ([-+0-9.Ee]+)", stripped)
        if geo and "," in geo.group(2):
            body_index = int(geo.group(1))
            component = int(geo.group(2).rsplit(",", 1)[1])
            scale = fuselage_scale if body_index == 0 else nacelle_scale
            value = float(geo.group(3)) * scale[component]
            result.append(f"P _body/{body_index}/_geo_xyz/{geo.group(2)} {f(value)}\n")
            continue

        if stripped.startswith("P "):
            parts = stripped.split(" ", 2)
            if len(parts) == 3 and parts[1] in replacements:
                result.append(f"P {parts[1]} {replacements[parts[1]]}\n")
                found.add(parts[1])
                continue

        result.append(line)

    missing = sorted(set(replacements) - found)
    if missing:
        raise RuntimeError("Template lacks required properties:\n" + "\n".join(missing))
    if not inserted_objects:
        raise RuntimeError("Template has no object attachment block")

    # Polygon-offset decals must follow their panel surfaces. Apply this to
    # the final attachment list so full builds, focused refreshes, and the
    # separately supplied cockpit control object share the same ordering.
    result = reorder_acf_attachments("".join(result).encode("latin1")).decode("latin1").splitlines(keepends=True)

    report = {
        "template": str(template),
        "replacement_count": len(found),
        "removed_template_object_attachments": True,
        "removed_template_3d_panel": True,
        "replacement_3d_panel": bool(panel_3d_lines),
        "visible_objects": order_cockpit_attachments([
            *(f"objects/{path}" for path in legacy_paths),
            *(f"objects/{path}" for path in exterior_object_paths),
            *(f"objects/{path}" for path in interior_object_paths),
            *((f"objects/{cockpit_object_path}",) if cockpit_object_path else ()),
        ]),
        "main_wing_area_m2": 841.7395024875,
        "main_wing_span_m": 79.75092,
        "status": "development-flight-model-not-flight-tested",
    }
    return result, report


def copy_tree_files(source: Path, destination: Path) -> None:
    if not source.is_dir():
        raise FileNotFoundError(source)
    destination.mkdir(parents=True, exist_ok=True)
    clear_extended_attributes(destination)
    for entry in source.iterdir():
        if entry.name.startswith("._"):
            continue
        # The MSFS source includes DX10/BC7 DDS sidecars next to portable PNG
        # textures. X-Plane 12 on macOS probes the DDS first, cannot decode
        # these particular files, and presents a damaged-aircraft warning
        # instead of falling back cleanly. Keep the PNG whenever both formats
        # exist; X-Plane can load it on macOS and Windows.
        if entry.suffix.casefold() == ".dds" and entry.with_suffix(".png").is_file():
            continue
        target = destination / entry.name
        if entry.is_dir():
            copy_tree_files(entry, target)
        else:
            # Preserve file bytes, not macOS extended attributes. ExFAT stores
            # those attributes as visible AppleDouble files that X-Plane may
            # try to index as aircraft assets.
            shutil.copyfile(entry, target)
            clear_extended_attributes(target)
    clear_extended_attributes(destination)
    # On some macOS non-APFS volumes the provenance xattr is materialized as a
    # separate AppleDouble file and cannot be cleared through removexattr.
    # These are generated metadata, not aircraft assets.
    for sidecar in destination.glob('._*'):
        if sidecar.is_file():
            sidecar.unlink()


def clear_extended_attributes(path: Path) -> None:
    """Avoid AppleDouble sidecars when staging onto non-APFS build volumes."""
    try:
        for attribute in os.listxattr(path):
            os.removexattr(path, attribute)
    except (AttributeError, OSError):
        # Other platforms and filesystems may not expose extended attributes.
        pass


def validate_fmod_inputs(snd: Path | None, bank_directory: Path | None) -> list[Path]:
    """Return the FMOD bank files after rejecting incomplete packages."""
    if (snd is None) != (bank_directory is None):
        raise ValueError("--fmod-snd and --fmod-bank-dir must be provided together")
    if snd is None or bank_directory is None:
        return []
    if snd.name != "A380X-XP12.snd" or not snd.is_file():
        raise FileNotFoundError(f"Expected generated A380X-XP12.snd, got {snd}")
    if not bank_directory.is_dir():
        raise FileNotFoundError(bank_directory)
    required = [bank_directory / "Master Bank.bank", bank_directory / "GUIDs.txt"]
    missing = [path for path in required if not path.is_file()]
    if missing:
        raise FileNotFoundError("Incomplete FMOD build: " + ", ".join(map(str, missing)))
    banks = sorted(path for path in bank_directory.glob("*.bank") if not path.name.startswith("._"))
    guid_text = required[1].read_text(encoding="utf-8", errors="replace")
    guid_objects = set(re.findall(r"\b(?:event|snapshot):/[^\r\n]+", guid_text))
    attached = set(re.findall(
        r"^(?:EVENT_NAME|SNAPSHOT_NAME)\s+(.+)$",
        snd.read_text(encoding="utf-8", errors="replace"),
        re.M,
    ))
    missing_objects = sorted(attached - guid_objects)
    if missing_objects:
        raise ValueError("FMOD GUIDs.txt lacks attached objects: " + ", ".join(missing_objects))
    return banks


def copy_fmod_package(snd: Path, bank_directory: Path, banks: list[Path], output: Path) -> None:
    destination = output / "fmod"
    if destination.exists():
        shutil.rmtree(destination)
    destination.mkdir(parents=True)
    shutil.copy2(snd, destination / snd.name)
    shutil.copy2(bank_directory / "GUIDs.txt", destination / "GUIDs.txt")
    for bank in banks:
        shutil.copy2(bank, destination / bank.name)


def copy_obj_with_package_texture_paths(source: Path, destination: Path) -> None:
    """Copy an OBJ while fixing paths for output/objects/gear-body-lh/."""
    with source.open("r", encoding="utf-8", errors="strict") as src, destination.open(
        "w", encoding="utf-8", newline="\n"
    ) as dst:
        for line in src:
            if line.strip() == "GLOBAL_cockpit_lit":
                continue
            if re.match(r"^TEXTURE(?:_LIT|_NORMAL|_MAP)?[ \t]", line):
                line = line.replace("../textures/gear-body-lh/", "../../textures/gear-body-lh/")
            dst.write(line)


def copy_exterior_obj(
    source: Path,
    destination: Path,
    texture_source: Path,
    texture_group: str,
    namespace: str = "exterior",
    *, hydraulic_surfaces: bool = False,
) -> set[str]:
    """Copy an OBJ and return only the textures it actually references."""
    referenced = set()
    # Older cached exterior exports retain native/legacy control refs. Apply
    # the same final binding during packaging; future fresh exports already
    # contain these refs from animation_datarefs.json. Cockpit inputs are scoped out.
    surface_mapping = {}
    if hydraulic_surfaces and namespace == "exterior" and texture_group in ("wings", "fuselage"):
        from bind_hydraulic_surfaces import AILERONS, SPOILERS, TAIL, EXPECTED_FILES
        if source.name in EXPECTED_FILES[texture_group]:
            surface_mapping = TAIL if texture_group == "fuselage" else {**AILERONS, **SPOILERS}
    surface_header = re.compile(r"^([ \t]*ANIM_(?:rotate|trans)_begin[^\r\n#]*?)([^\s#]+)([ \t]*(?:#[^\r\n]*)?(?:\r?\n)?)$")
    texture_pattern = re.compile(
        r"^(TEXTURE(?:_LIT|_NORMAL)?|TEXTURE_MAP[ \t]+[^ \t]+)[ \t]+(.+?)\s*$"
    )
    destination.parent.mkdir(parents=True, exist_ok=True)
    with source.open("r", encoding="utf-8", errors="strict") as src, destination.open(
        "w", encoding="utf-8", newline="\n"
    ) as dst:
        for line in src:
            if line.strip() == "GLOBAL_cockpit_lit":
                continue
            match = texture_pattern.match(line)
            if match:
                filename = Path(match.group(2)).name
                if filename and filename.upper() != "NONE":
                    package_texture = texture_source / filename
                    if not package_texture.is_file():
                        raise FileNotFoundError(
                            f"{source.name} references missing texture {package_texture}"
                        )
                    referenced.add(filename)
                    line = (
                        f"{match.group(1)} ../../../textures/{namespace}/"
                        f"{texture_group}/{filename}\n"
                    )
            header = surface_header.match(line) if surface_mapping else None
            if header and header.group(2) in surface_mapping:
                line = header.group(1) + surface_mapping[header.group(2)] + header.group(3)
            dst.write(line)
    return referenced


def exterior_group(
    name: str,
    object_directory: Path | None,
    texture_directory: Path | None,
) -> tuple[str, Path, Path, list[Path]] | None:
    if object_directory is None and texture_directory is None:
        return None
    if object_directory is None or texture_directory is None:
        raise ValueError(f"Both {name} object and texture directories are required")
    if not object_directory.is_dir():
        raise FileNotFoundError(object_directory)
    if not texture_directory.is_dir():
        raise FileNotFoundError(texture_directory)
    objects = sorted(
        path for path in object_directory.glob("*.obj") if not path.name.startswith("._")
    )
    if not objects:
        raise FileNotFoundError(f"No OBJ files found under {object_directory}")
    return name, object_directory, texture_directory, objects


def preflight_textures(objects: list[Path], texture_dir: Path) -> None:
    """Fail on missing inputs before replacing any generated package assets."""
    for obj in objects:
        with obj.open() as source:
            for line in source:
                if line.startswith('POINT_COUNTS'):
                    break
                if not line.startswith('TEXTURE'):
                    continue
                words = line.split()
                if len(words) < 2 or words[-1].upper() == 'NONE':
                    continue
                filename = Path(words[-1]).name
                if not (texture_dir / filename).is_file():
                    raise FileNotFoundError(f'{obj}: missing texture {texture_dir / filename}')


def exterior_requires_surface_provider(aircraft: Path) -> bool:
    """Accept only complete reviewed legacy and/or hydraulic animation sets."""
    refs = set()
    for group in ('wings', 'fuselage'):
        for path in sorted((aircraft / 'objects/exterior' / group).glob('*.obj')):
            if path.name.startswith('._'):
                continue
            with path.open() as stream:
                for line in stream:
                    words = line.split('#', 1)[0].split()
                    if words and words[0].startswith('ANIM_'):
                        refs.update(word for word in words[1:] if
                                    word.startswith(('a380x/xp12/visual/aileron_',
                                                     'a380x/xp12/hydraulics/')))
    for prefix, expected in (('a380x/xp12/visual/aileron_', set(AILERON_VISUAL_DATAREFS)),
                             ('a380x/xp12/hydraulics/', set(HYDRAULIC_DATAREFS))):
        actual = {ref for ref in refs if ref.startswith(prefix)}
        if actual and actual != expected:
            raise ValueError(f'Incomplete or unexpected exterior surface dataref set: {prefix}')
    return bool(refs)


def group_is_selected(name: str, refresh_groups: list[str]) -> bool:
    """Return whether a generated asset group belongs to this invocation."""
    return not refresh_groups or name in refresh_groups


def interior_sources(
    name: str,
    object_directory: Path | None,
    refresh_groups: list[str],
) -> list[Path]:
    """Load an interior group only when a full build or its refresh was requested.

    A focused refresh must not inspect unrelated source directories. This is
    important on the split-volume development setup, where an unrelated export
    may be temporarily absent while the cockpit controls remain refreshable.
    """
    if not group_is_selected(name, refresh_groups):
        return []
    if object_directory is None:
        if refresh_groups:
            raise ValueError(f'--refresh-group {name} requires its object directory')
        return []
    if not object_directory.is_dir():
        raise FileNotFoundError(object_directory)
    sources = sorted(
        path for path in object_directory.glob("*.obj") if not path.name.startswith("._")
    )
    if not sources:
        raise FileNotFoundError(f"No OBJ files found under {object_directory}")
    return sources


def existing_attachment_paths(acf: Path) -> tuple[list[str], list[str], str | None]:
    """Read package-relative attachments used by an existing focused build."""
    text = acf.read_text(encoding='latin1')
    paths = [
        value
        for _index, value in re.findall(
            r'^P _obja/(\d+)/_v10_att_file_stl (.+)$', text, re.M
        )
    ]
    exterior = [path for path in paths if path.startswith('exterior/')]
    interior = [
        path for path in paths
        if path.startswith('interior/') and not path.startswith('interior/cockpit-controls/')
    ]
    controls = next(
        (path for path in paths if path.startswith('interior/cockpit-controls/')),
        None,
    )
    return exterior, interior, controls


def existing_panel_3d_lines(acf: Path) -> list[str] | None:
    """Recover the installed panel definition for a non-panel group refresh."""
    text = acf.read_text(encoding='latin1')
    match = re.search(r'^PANEL_3D_BEGIN\r?\n(.*?)^PANEL_3D_END$', text, re.M | re.S)
    if not match:
        return None
    return match.group(1).splitlines(keepends=True)


def merge_refreshed_paths(
    existing: list[str],
    replacements: dict[str, list[str]],
    namespace: str,
) -> list[str]:
    """Replace selected package groups while preserving every unselected path."""
    inserted: set[str] = set()
    merged: list[str] = []
    prefix = namespace + '/'
    for path in existing:
        parts = path.split('/', 2)
        group = parts[1] if len(parts) == 3 and path.startswith(prefix) else None
        if group not in replacements:
            merged.append(path)
            continue
        if group not in inserted:
            merged.extend(replacements[group])
            inserted.add(group)
    for group, paths in replacements.items():
        if group not in inserted:
            merged.extend(paths)
    return merged


def attach_mfd_screens(paths: list[str]) -> list[str]:
    """Attach the visible MFD screens once, directly after the dark display faces.

    Idempotent for focused refreshes: an existing attachment is moved, never
    duplicated. Without the dark-face object it is appended; the attachment
    reorder still keeps it ahead of the cockpit-panel decals.
    """
    result = [path for path in paths if path != MFD_SCREENS_ATTACHMENT]
    if MFD_SCREENS_ANCHOR in result:
        result.insert(result.index(MFD_SCREENS_ANCHOR) + 1, MFD_SCREENS_ATTACHMENT)
    else:
        result.append(MFD_SCREENS_ATTACHMENT)
    return result


def mfd_screens_texture(obj: Path) -> Path:
    """Preflight the generated MFD screen object; return its albedo texture."""
    if obj.name != MFD_SCREENS_OBJECT:
        raise ValueError(f'--mfd-screens-object must be named {MFD_SCREENS_OBJECT}: {obj}')
    if not obj.is_file():
        raise FileNotFoundError(obj)
    textures = [line.split(None, 1)[1].strip()
                for line in obj.read_text(encoding='ascii').splitlines()
                if line.startswith('TEXTURE') and len(line.split()) > 1]
    if len(textures) != 1 or not textures[0].startswith(MFD_SCREENS_TEXTURE_PREFIX) \
            or '/' in textures[0][len(MFD_SCREENS_TEXTURE_PREFIX):]:
        raise ValueError(f'{obj}: expected one TEXTURE under {MFD_SCREENS_TEXTURE_PREFIX}')
    texture = obj.parent / textures[0][len(MFD_SCREENS_TEXTURE_PREFIX):]
    if not texture.is_file():
        raise FileNotFoundError(f'{obj}: missing texture {texture}')
    if 'ATTR_cockpit_device' not in obj.read_text(encoding='ascii'):
        raise ValueError(f'{obj}: no ATTR_cockpit_device screens')
    return texture


def write_empty_2d_panel(output: Path) -> None:
    """Suppress X-Plane's built-in jet panel art, leaving attached 3-D geometry.

    A zero-geometry cockpit marker alone does not suppress the generic 2-D
    artwork in X-Plane 12.4.3. Supply a transparent custom panel as well.
    This is a blank engine-control texture, not cockpit artwork.
    """
    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data) & 0xffffffff)
    width = height = 1024
    raw = (b'\0' + b'\0' * (width * 4)) * height
    png = (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>2I5B', width, height, 8, 6, 0, 0, 0))
           + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))
    panel = output / 'cockpit' / '-PANELS-' / 'Panel.png'
    panel.parent.mkdir(parents=True, exist_ok=True)
    panel.write_bytes(png)


