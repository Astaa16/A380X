FT_PER_M = 3.280839895013123
KG_TO_LB = 2.2046226218487757
MSFS_NOSE_LONGITUDINAL_FT = 115.108
# X-Plane's cached equilibrium height is the aircraft-reference CG height
# above the contact plane, not MSFS's static-CG-height field by itself.  The
# source CG is 2.8 ft above its datum. The original body-main contact was
# 15.75 ft below it, but X-Plane's measured body-tire compression exceeded
# the wing tires' by about 0.16 m and left the nose airborne.  The X-Plane
# body gear is extended 0.42 ft below the MSFS contact point to offset most
# of that differential. A live run at -15.75 ft nose contact still left the
# nose unloaded at 1.03 degrees. A subsequent cached-model probe did not
# validate the -17.05 ft candidate. Set the next ground-test candidate to
# -17.95 ft, then verify its actual contact force in a fresh X-Plane load.
# The initial pose follows the lowest of the nose and body-main contacts.
# Using MSFS's 14.30 ft static-CG-height field instead placed the model about
# 1.30 m into the runway and produced a
# repeatable ~16 g startup impulse.
XPLANE_BODY_CONTACT_FT = -16.17
XPLANE_NOSE_CONTACT_FT = -17.95
XPLANE_EQUILIBRIUM_HEIGHT_FT = 2.8 - min(XPLANE_BODY_CONTACT_FT, XPLANE_NOSE_CONTACT_FT)
XPLANE_EQUILIBRIUM_PITCH_DEG = 0.0
# Deployed nose-tyre mesh bottom in its OBJ coordinate system, measured by
# audit_gear_mesh_alignment.py. Shift the moving nose assembly in the ACF so
# its visible tyre and physical contact share the same datum. The fixed bay
# remains attached to the fuselage at its original coordinate.
NOSE_TYRE_MESH_BOTTOM_M = -4.225983
NOSE_ASSEMBLY_Y_FT = XPLANE_NOSE_CONTACT_FT - NOSE_TYRE_MESH_BOTTOM_M * FT_PER_M

EXTERIOR_GROUPS = (
    "fuselage", "wings", "gear-body-lh", "gear-body-rh", "gear-wing-lh",
    "gear-wing-rh", "gear-nose",
)
INTERIOR_GROUPS = ("cockpit", "cabin", "cabin-seats", "cockpit-panels")
REFRESH_GROUPS = (*EXTERIOR_GROUPS, *INTERIOR_GROUPS, "cockpit-controls")
# Visible MFD plugin-device screens (docs/mfd-spec/08 section 10.3, 09 section 1.10).
# Generated by build_cockpit_controls.py --mfd-screens-output next to its black
