def load_census():
    return json.loads(CENSUS.read_text())


def classify(row):
    """(class, source, dump_check) for one census row; KeyError when no rule matches."""
    for pattern, kind, source, nocheck in _COMPILED:
        if pattern.match(row['name']):
            return kind, source, not nocheck
    raise KeyError('unclassified SD variable: %s / %s' % (row['page'], row['name']))


def frame_key(row):
    """Key a380x_sd_data.inc publishes for this census row (SDv2 bus topics as ev:<topic>)."""
    return 'ev:' + row['name'] if row['page'] == 'F/CTL' else row['name']


def coverage(rows=None):
    rows = rows if rows is not None else load_census()
    table = OrderedDict((page, Counter()) for page in PAGE_ORDER)
    for row in rows:
        table.setdefault(row['page'], Counter())[classify(row)[0]] += 1
    return table


def _escape(text):
    return str(text).replace('|', '\\|').replace('\n', ' ')


def render():
    rows = load_census()
    lines = [BEGIN, '', '### Coverage', '',
             '| Page | live | derived | ncd | missing | bundle | n/a | total |',
             '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |']
    totals = Counter()
    for page, counts in coverage(rows).items():
        totals.update(counts)
        lines.append('| %s | %d | %d | %d | %d | %d | %d | %d |' % (
            page, counts['live'], counts['derived'], counts['ncd'], counts['missing'], counts['bundle'],
            counts['n/a'], sum(counts.values())))
    lines.append('| **all** | %d | %d | %d | %d | %d | %d | %d |' % (
        totals['live'], totals['derived'], totals['ncd'], totals['missing'], totals['bundle'], totals['n/a'],
        sum(totals.values())))
    for page in PAGE_ORDER:
        page_rows = [row for row in rows if row['page'] == page]
        lines += ['', '### %s' % page, '', '| FBW variable | read as | class | port source |', '| --- | --- | --- | --- |']
        for row in page_rows:
            kind, source, _ = classify(row)
            read = row.get('hook') or ''
            if row.get('unit'):
                read += ' `%s`' % row['unit']
            if row.get('simvar'):
                read += ' (%s)' % row['simvar']
            lines.append('| `%s` | %s | %s | %s |' % (_escape(row['name']), _escape(read), kind, _escape(source)))
    lines += ['', END]
    return '\n'.join(lines)


def write_doc():
    text = DOC.read_text()
    start, end = text.index(BEGIN), text.index(END) + len(END)
    DOC.write_text(text[:start] + render() + text[end:])


def doc_is_current():
    text = DOC.read_text()
    start, end = text.index(BEGIN), text.index(END) + len(END)
    return text[start:end] == render()


