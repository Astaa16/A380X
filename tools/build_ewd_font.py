#!/usr/bin/env python3
"""Bake the pinned FBW EIS font into an embedded alpha atlas for native EWD text."""
from pathlib import Path
import hashlib
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1] / 'native' / 'avionics'
SOURCE = ROOT / 'fonts' / 'FBW-Display-EIS-A380.ttf'
SIZE, WIDTH, HEIGHT = 64, 1024, 512


def main():
    font = ImageFont.truetype(str(SOURCE), SIZE)
    atlas = Image.new('L', (WIDTH, HEIGHT), 0)
    draw = ImageDraw.Draw(atlas)
    glyphs = []
    for index, code in enumerate([*range(32, 127), 176]):
        char = chr(code)
        x, y = index % 16 * 64 + 2, index // 16 * 80 + 2
        left, top, right, bottom = font.getbbox(char, anchor='ls')
        if right-left > 60 or bottom-top > 76:
            raise ValueError(f'Glyph does not fit: {char}')
        draw.text((x-left, y-top), char, font=font, fill=255, anchor='ls')
        glyphs.append((code, x, y, right-left, bottom-top, left, top, font.getlength(char)))
    raw = atlas.tobytes()
    runs = []
    for value in raw:
        if runs and runs[-1][1] == value and runs[-1][0] < 255:
            runs[-1][0] += 1
        else:
            runs.append([1, value])
    encoded = [v for run in runs for v in run]
    header = [
        '/* SPDX-License-Identifier: GPL-3.0-or-later',
        ' * Generated by tools/build_ewd_font.py from FBW-Display-EIS-A380.ttf.',
        f' * Font SHA-256: {hashlib.sha256(SOURCE.read_bytes()).hexdigest()}',
        ' */',
        'typedef struct { unsigned short code,x,y,w,h; short left,top; float advance; } EwdGlyph;',
        f'enum {{ EWD_FONT_SIZE={SIZE}, EWD_FONT_WIDTH={WIDTH}, EWD_FONT_HEIGHT={HEIGHT} }};',
        'static const EwdGlyph ewd_glyphs[] = {',
        *['    {%d,%d,%d,%d,%d,%d,%d,%.6ff},' % g for g in glyphs],
        '};', 'static const unsigned char ewd_font_runs[] = {',
        *['    '+','.join(map(str,encoded[i:i+32]))+',' for i in range(0,len(encoded),32)],
        '};', '',
    ]
    (ROOT / 'a380x_ewd_font.h').write_text('\n'.join(header))
    print(f'{len(glyphs)} glyphs, {len(encoded)} RLE bytes')


if __name__ == '__main__':
    main()
