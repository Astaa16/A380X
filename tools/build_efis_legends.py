#!/usr/bin/env python3
"""Extract the FBW A380X EFIS CP dot-matrix legends into a compact C table.

FlyByWire draws each ND-filter legend as a 1244 x 352 PNG: a 24 x 7 grid of 40 px
square dots on a 52 px pitch, lit dots opaque white and unlit dots faint grey
(alpha 38). The native renderer redraws exactly those dots as geometry, so the
legends stay crisp at any cockpit-texture resolution.
"""
from pathlib import Path
import hashlib
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = (ROOT.parent / 'upstream-aircraft/fbw-a380x/src/base/flybywire-aircraft-a380-842'
          / 'html_ui/Images/fbw-a380x/fcu')
OUTPUT = ROOT / 'native/avionics/a380x_efis_legends.h'
NAMES = ('CSTR', 'WPT', 'VORD', 'NDB', 'ARPT', 'WX', 'TERR', 'TRAF',
         'VOR1', 'VOR2', 'ADF1', 'ADF2', 'POINTER1', 'POINTER2')
COLS, ROWS, PITCH, DOT = 24, 7, 52, 40


def grid(path):
    image = Image.open(path).convert('RGBA')
    if image.size != (1244, 352):
        raise ValueError(f'Unexpected legend size {image.size}: {path.name}')
    rows = []
    for row in range(ROWS):
        cells = []
        for col in range(COLS):
            r, g, b, a = image.getpixel((col * PITCH + DOT // 2, row * PITCH + DOT // 2))
            cells.append(2 if a > 200 and min(r, g, b) > 200 else 1 if a > 0 else 0)
        rows.append(cells)
    return rows


def main():
    lines = ['/* SPDX-License-Identifier: GPL-3.0-or-later',
             ' * Generated by tools/build_efis_legends.py from the pinned FlyByWire A380X',
             ' * html_ui/Images/fbw-a380x/fcu legends. 0 = no dot, 1 = unlit dot, 2 = lit dot.']
    for name in NAMES:
        digest = hashlib.sha256((SOURCE / f'{name}.png').read_bytes()).hexdigest()
        lines.append(f' * {name}.png SHA-256: {digest}')
    lines += [' */', '#ifndef A380X_EFIS_LEGENDS_H', '#define A380X_EFIS_LEGENDS_H',
              f'enum {{ EFIS_LEGEND_COLS={COLS}, EFIS_LEGEND_ROWS={ROWS}, EFIS_LEGEND_PITCH={PITCH}, EFIS_LEGEND_DOT={DOT} }};',
              'enum { ' + ', '.join(f'EFIS_LEGEND_{n}' for n in NAMES) + ', EFIS_LEGEND_COUNT };',
              'static const unsigned char efis_legends[EFIS_LEGEND_COUNT][EFIS_LEGEND_ROWS][EFIS_LEGEND_COLS] = {']
    for name in NAMES:
        rows = grid(SOURCE / f'{name}.png')
        lines.append('    { /* ' + name + ' */')
        lines += ['        {' + ','.join(map(str, row)) + '},' for row in rows]
        lines.append('    },')
    lines += ['};', '#endif', '']
    OUTPUT.write_text('\n'.join(lines))
    print(f'{len(NAMES)} legends -> {OUTPUT.name}')


if __name__ == '__main__':
    main()
