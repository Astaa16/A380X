#!/usr/bin/env python3
"""Bake the pinned FBW A380X ISIS font into an embedded alpha atlas for the native ISIS.

FlyByWire's ISISlegacy (style.scss) renders every text with the "Ecam" face, which is
html_ui/Fonts/fbw-a380x/ISISFontTemporary.ttf. The native ISIS draws FBW's 512-unit SVG
at 2 device texels per unit (1024 x 1024); the attitude display group carries FBW's extra
`scale(1.1)`, so its texts are drawn at 2.2 texels per unit. Every face below is rasterised
at exactly the texel size it is drawn at (FBW CSS px x 2 or x 2.2), so glyphs are copied 1:1.

Private byte codes: 0x01 = U+2191 (up arrow), 0x02 = U+2192 (right arrow), 0x03 = U+2193.
"""
from pathlib import Path
import hashlib
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1] / 'native' / 'avionics'
FONT = ROOT / 'fonts' / 'ISISFontTemporary.ttf'
OUTPUT = ROOT / 'a380x_isis_font.h'
WIDTH = 1024
UPPER = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'
DIGITS = '0123456789'
ARROWS = {'\x01': '↑', '\x02': '→', '\x03': '↓'}
# name, texel em size (FBW px x device scale), characters
FACES = (
    ('F56', 28 * 2.0, UPPER + DIGITS + '/.-()\x01\x02\x03 '),      # self-test baro, MENU items
    ('F60', 30 * 2.0, 'INT' + DIGITS + 's '),                       # self-test INIT countdown (FontMedium)
    ('F61_6', 28 * 2.2, DIGITS + '/. '),                            # pitch scale, tens drum, QNH (attitude group)
    ('F64', 32 * 2.0, UPPER + DIGITS + '/.-()+\x01\x02\x03 '),      # BUGS / MENU pages (FontLarge)
    ('F66', 30 * 2.2, DIGITS + '.ATSNEGMs '),                       # tapes, Mach, metric altitude, ATT 10s
    ('F72', 36 * 2.0, 'ADLPST '),                                   # ATT / SPD / ALT flags, self-test STD
    ('F79_2', 36 * 2.2, DIGITS + 'NEGSTD '),                        # altitude drums, NEG, STD
    ('F32', 16 * 2.0, '(+-) '),                                     # BUGS page (+) / (-)
)


def render_glyph(font, size, char):
    """Return (left, top, image) of the glyph relative to the pen origin on the baseline."""
    pad = int(2 * size)
    probe = Image.new('L', (4 * pad, 4 * pad), 0)
    ImageDraw.Draw(probe).text((pad, pad), char, font=font, fill=255, anchor='ls')
    box = probe.getbbox()
    if box is None:
        return 0, 0, None
    return box[0] - pad, pad - box[1], probe.crop(box)


def main():
    placed, glyph_rows, x, y, row_h = [], [], 2, 2, 0
    upem_font = __import__('fontTools.ttLib', fromlist=['TTFont']).TTFont(str(FONT))
    cap = upem_font['OS/2'].sCapHeight / upem_font['head'].unitsPerEm
    for face_index, (_name, size, chars) in enumerate(FACES):
        font = ImageFont.truetype(str(FONT), size)
        for char in chars:
            source = ARROWS.get(char, char)
            left, top, crop = render_glyph(font, size, source)
            w, h = (crop.width, crop.height) if crop else (0, 0)
            if x + w + 2 > WIDTH:
                x, y, row_h = 2, y + row_h + 2, 0
            glyph_rows.append((face_index, ord(char), x, y, w, h, left, top, font.getlength(source)))
            if crop:
                placed.append((crop, x, y))
            x += w + 2
            row_h = max(row_h, h)
    height = 1 << (y + row_h + 2 - 1).bit_length()
    atlas = Image.new('L', (WIDTH, height), 0)
    for crop, ox, oy in placed:
        atlas.paste(crop, (ox, oy))
    runs = []
    for value in atlas.tobytes():
        if runs and runs[-1][1] == value and runs[-1][0] < 255:
            runs[-1][0] += 1
        else:
            runs.append([1, value])
    encoded = [v for run in runs for v in run]
    lines = [
        '/* SPDX-License-Identifier: GPL-3.0-or-later',
        ' * Generated by tools/build_isis_font.py. Do not edit.',
        f' * ISISFontTemporary.ttf SHA-256: {hashlib.sha256(FONT.read_bytes()).hexdigest()}',
        ' * (FlyByWire "FBW Display-EIS A320", GPL-3.0, html_ui/Fonts/fbw-a380x/ISISFontTemporary.ttf)',
        ' */',
        '#ifndef A380X_ISIS_FONT_H',
        '#define A380X_ISIS_FONT_H',
        'typedef struct { unsigned char face, code; unsigned short x, y, w, h; short left, top; float advance; } IsisGlyph;',
        'enum { ' + ', '.join(f'ISIS_FACE_{n}' for n, *_ in FACES) + ', ISIS_FACE_COUNT };',
        'static const float isis_face_size[ISIS_FACE_COUNT] = { ' + ', '.join(f'{s:.1f}f' for _, s, _ in FACES) + ' };',
        f'static const float isis_font_cap_height = {cap:.6f}f; /* OS/2 sCapHeight / unitsPerEm */',
        f'enum {{ ISIS_FONT_WIDTH={WIDTH}, ISIS_FONT_HEIGHT={height} }};',
        'static const IsisGlyph isis_glyphs[] = {',
        *['    {%d,%d,%d,%d,%d,%d,%d,%d,%.6ff},' % g for g in glyph_rows],
        '};',
        'static const unsigned char isis_font_runs[] = {',
        *['    ' + ','.join(map(str, encoded[i:i + 32])) + ',' for i in range(0, len(encoded), 32)],
        '};',
        'static inline const IsisGlyph *isis_glyph_find(int face, unsigned char code)',
        '{',
        '    unsigned i;',
        '    for (i = 0; i < sizeof(isis_glyphs) / sizeof(isis_glyphs[0]); ++i)',
        '        if (isis_glyphs[i].face == face && isis_glyphs[i].code == code) return &isis_glyphs[i];',
        '    return 0;',
        '}',
        '#endif',
        '',
    ]
    OUTPUT.write_text('\n'.join(lines))
    print(f'{len(glyph_rows)} glyphs, atlas {WIDTH}x{height}, {len(encoded)} RLE bytes, cap {cap:.4f}')


if __name__ == '__main__':
    main()
