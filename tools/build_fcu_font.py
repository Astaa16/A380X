#!/usr/bin/env python3
"""Bake the pinned FBW A380 FCU fonts into an embedded alpha atlas for the AFS CP LCDs.

Faces are rasterised at the exact texel size they are drawn at (see a380x_fcu_render.inc),
so the cockpit texture never scales glyphs:
  value: FBW "Digital" (A380X_FCU.ttf) for SPD/MACH, HDG/TRK and ALT values.
  vs:    the same font, 0.76 x value size, for the V/S / FPA window.
  label: Poppins-SemiBold for SPD, MACH, HDG, TRK, TRUE, ALT, V/S, FPA, KT.
"""
from pathlib import Path
import hashlib
from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = Path(__file__).resolve().parents[1] / 'native' / 'avionics'
DIGITAL = ROOT / 'fonts' / 'A380X_FCU.ttf'
POPPINS = ROOT / 'fonts' / 'Poppins-SemiBold.ttf'
WIDTH = 1024
# name, file, pixel em, characters. 0xB0 is the degree sign.
FACES = (
    ('VALUE', DIGITAL, 121, '0123456789-+.~o\xb0 '),
    ('VS', DIGITAL, 92, '0123456789-+.~o '),
    ('LABEL', POPPINS, 48, 'ACDFGHKLMPRSTUV/E '),
    # EFIS CP baro window (384 x 244 texels): FBW BaroRefDisplay sizes 256 / 137.5 / 105 px
    # relative to each other, scaled to the measured value height of the reference capture.
    ('BARO_VALUE', DIGITAL, 136, '0123456789.Std '),
    ('BARO_PRESET', DIGITAL, 73, '0123456789. '),
    ('BARO_LABEL', POPPINS, 56, 'QNHFE '),
)


# LCD glow: the physical AFS CP segments bleed into each other. A 3-texel dilation
# closes the font's inter-segment gaps and a soft blur rounds the segment ends, as on
# the reference capture, without changing glyph metrics.
GLOW_DILATE = {'VALUE': 3, 'VS': 3, 'LABEL': 1, 'BARO_VALUE': 3, 'BARO_PRESET': 3, 'BARO_LABEL': 1}
GLOW_BLUR = {'VALUE': 1.1, 'VS': 0.9, 'LABEL': 0.5, 'BARO_VALUE': 1.2, 'BARO_PRESET': 0.8, 'BARO_LABEL': 0.5}


def render_glyph(font, size, char, name):
    """Return (left, top, image) of the glowed glyph relative to the pen origin on the baseline."""
    pad = 2 * size
    probe = Image.new('L', (4 * size, 4 * size), 0)
    ImageDraw.Draw(probe).text((pad, pad), char, font=font, fill=255, anchor='ls')
    if probe.getbbox() is None:
        return 0, 0, None
    if GLOW_DILATE[name] > 1:
        probe = probe.filter(ImageFilter.MaxFilter(GLOW_DILATE[name]))
    probe = probe.filter(ImageFilter.GaussianBlur(GLOW_BLUR[name]))
    probe = probe.point(lambda v: 0 if v < 4 else v)
    box = probe.getbbox()
    return box[0] - pad, box[1] - pad, probe.crop(box)


def main():
    placed, x, y, row_h = [], 2, 2, 0
    glyph_rows = []
    for face_index, (name, path, size, chars) in enumerate(FACES):
        font = ImageFont.truetype(str(path), size)
        for char in chars:
            left, top, crop = render_glyph(font, size, char, name)
            w, h = (crop.width, crop.height) if crop else (0, 0)
            if x + w + 2 > WIDTH:
                x, y, row_h = 2, y + row_h + 2, 0
            glyph_rows.append((face_index, ord(char), x, y, w, h, left, top, font.getlength(char)))
            if crop:
                placed.append((crop, x, y))
            x += w + 2
            row_h = max(row_h, h)
    height = 1 << (y + row_h + 2 - 1).bit_length()
    atlas = Image.new('L', (WIDTH, height), 0)
    for crop, ox, oy in placed:
        atlas.paste(crop, (ox, oy))
    raw = atlas.tobytes()
    runs = []
    for value in raw:
        if runs and runs[-1][1] == value and runs[-1][0] < 255:
            runs[-1][0] += 1
        else:
            runs.append([1, value])
    encoded = [v for run in runs for v in run]
    lines = [
        '/* SPDX-License-Identifier: GPL-3.0-or-later',
        ' * Generated by tools/build_fcu_font.py. Do not edit.',
        f' * A380X_FCU.ttf SHA-256: {hashlib.sha256(DIGITAL.read_bytes()).hexdigest()}',
        f' * Poppins-SemiBold.ttf SHA-256: {hashlib.sha256(POPPINS.read_bytes()).hexdigest()} (SIL OFL 1.1)',
        ' */',
        '#ifndef A380X_FCU_FONT_H',
        '#define A380X_FCU_FONT_H',
        'typedef struct { unsigned char face, code; unsigned short x, y, w, h; short left, top; float advance; } FcuGlyph;',
        'enum { ' + ', '.join(f'FCU_FACE_{n}' for n, *_ in FACES) + ', FCU_FACE_COUNT };',
        'static const float fcu_face_size[FCU_FACE_COUNT] = { ' + ', '.join(f'{s}.0f' for _, _, s, _ in FACES) + ' };',
        f'enum {{ FCU_FONT_WIDTH={WIDTH}, FCU_FONT_HEIGHT={height} }};',
        'static const FcuGlyph fcu_glyphs[] = {',
        *['    {%d,%d,%d,%d,%d,%d,%d,%d,%.6ff},' % g for g in glyph_rows],
        '};',
        'static const unsigned char fcu_font_runs[] = {',
        *['    ' + ','.join(map(str, encoded[i:i + 32])) + ',' for i in range(0, len(encoded), 32)],
        '};',
        'static inline const FcuGlyph *fcu_glyph_find(int face, unsigned char code)',
        '{',
        '    unsigned i;',
        '    for (i = 0; i < sizeof(fcu_glyphs) / sizeof(fcu_glyphs[0]); ++i)',
        '        if (fcu_glyphs[i].face == face && fcu_glyphs[i].code == code) return &fcu_glyphs[i];',
        '    return 0;',
        '}',
        'static inline float fcu_text_width(int face, const char *text)',
        '{',
        '    float width = 0;',
        '    for (; *text; ++text) { const FcuGlyph *g = fcu_glyph_find(face, (unsigned char)*text); if (g) width += g->advance; }',
        '    return width;',
        '}',
        '#endif',
        '',
    ]
    (ROOT / 'a380x_fcu_font.h').write_text('\n'.join(lines))
    print(f'{len(glyph_rows)} glyphs, atlas {WIDTH}x{height}, {len(encoded)} RLE bytes')


if __name__ == '__main__':
    main()
